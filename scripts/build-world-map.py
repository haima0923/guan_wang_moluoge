"""Generate a local vector basemap from public-domain Natural Earth coastlines."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
source = json.loads((ROOT / 'scripts/map-data/ne_110m_land.geojson').read_text())
def project(lon, lat):
    return 30 + (lon + 180) * 2.6, 24 + (85 - lat) * 2.6
paths = []
for feature in source['features']:
    geometry = feature['geometry']
    polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
    for polygon in polygons:
        if max(point[1] for point in polygon[0]) < -60:
            continue  # Antarctica is outside this freight overview.
        for ring in polygon:
            points = [project(*point[:2]) for point in ring]
            paths.append('M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in points) + 'Z')
output = '// Natural Earth 1:110m land; public domain. Generated by scripts/build-world-map.py.\n'
output += 'export const WORLD_LAND_PATH = ' + json.dumps(''.join(paths)) + ';\n'
(ROOT / 'public/assets/world-land.js').write_text(output)
print(f'Generated world basemap: {len(paths)} rings, {len(output):,} bytes.')
